TRACKS_BY_SLUG: dict[str, dict[str, Any]] = {t["slug"]: t for t in TRACKS}


def get_track(slug: str) -> dict[str, Any]:
    if slug not in TRACKS_BY_SLUG:
        raise KeyError(f"Unknown track slug '{slug}'. Available: {', '.join(TRACKS_BY_SLUG.keys())}")
    return TRACKS_BY_SLUG[slug]


def probe_duration(filepath: Path) -> float:
    try:
        out = subprocess.check_output(
            [
                "ffprobe", "-v", "error",
                "-show_entries", "format=duration",
                "-of", "default=noprint_wrappers=1:nokey=1",
                str(filepath),
            ],
            text=True,
            timeout=5,
        ).strip()
        return round(float(out), 2)
    except Exception:
        return 3600.0


def build_public_tracks(web_dir: Path | None = None) -> list[dict[str, Any]]:
    """Build web-player JSON entries directly from TRACKS catalog."""
    wdir = Path(web_dir) if web_dir else WEB_DIR
    audio_dir = wdir / "audio"
    out = []
    for idx, t in enumerate(TRACKS, start=1):
        fpath = audio_dir / t["filename"]
        if fpath.is_file():
            dur = probe_duration(fpath)
            size_mb = round(fpath.stat().st_size / (1024 * 1024), 1)
        else:
            dur = 3600.0
            size_mb = 82.4

        entry: dict[str, Any] = {
            "id": f"track-{idx}",
            "slug": t["slug"],
            "filename": t["filename"],
            "cover": t["cover"],
            "title": t["title"],
            "subtitle": t["subtitle"],
            "category": t["category"],
            "mood": t["mood"],
            "band": t["band"],
            "beatHz": t["beatHz"],
            "binaural": t["binaural"],
            "binauralL": t["binauralL"],
            "binauralR": t["binauralR"],
            "bpm": t["bpm"],
            "key": t["key"],
            "description": t["description"],
            "palette": t["palette"],
            "movementsCount": t["movementsCount"],
            "visual": t["visual"],
            "duration": dur,
            "sizeMb": size_mb,
            "url": "audio/" + urllib.parse.quote(t["filename"]),
        }
        if t.get("featured"):
            entry["featured"] = True
        if t.get("coverLoop"):
            entry["coverLoop"] = t["coverLoop"]
        out.append(entry)
    return out


def write_tracks_json(web_dir: Path | None = None) -> Path:
    wdir = Path(web_dir) if web_dir else WEB_DIR
    wdir.mkdir(parents=True, exist_ok=True)
    out_path = wdir / "tracks.json"
    data = {"tracks": build_public_tracks(wdir)}
    out_path.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return out_path
